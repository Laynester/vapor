/**
 * Generic browser launcher for a compiled project.
 *
 * The launcher deliberately knows only the compiler's output contract: `manifest.json`
 * names the entry, `app.js` registers generated classes, and optional `app.pop` bundles
 * provide assets. It never names an application class or asset.
 */

export interface BrowserBootOptions {
  /** Bundle filename emitted by the compiler. */
  bundle?: string;
  /** Asset archive loaded before the entry constructor runs. */
  assets?: string;
  /** Canvas id used as the stage viewport. */
  canvasId?: string;
  /** Optional classic host script loaded before the launcher. */
  host?: string;
}

function json(value: string): string {
  return JSON.stringify(value);
}

/** Emits the ES module that starts a compiled browser project. */
export function browserBoot(options: BrowserBootOptions = {}): string {
  const bundle = options.bundle ?? "app.js";
  const assets = options.assets ?? "app.pop";
  const canvasId = options.canvasId ?? "stage";
  return `// Generated by as3js: generic browser launcher.
import "./${bundle}";
import {
  $createRoot,
  $dispatchMouseEvent,
  $flushEmbeddedAssets,
  $getClass,
  $renderDisplay,
  $runtimeClass,
  $setAssetManager,
  $setBaseUrl,
  $setExternalInterfaceBridge,
  $setExternalVariables,
  $setLoaderProgress,
  $setStageMovieSize,
  $setStageSize,
  $startFrameLoop,
  AssetManager,
  PopArchive,
} from "./runtime.js";

const canvas = document.getElementById(${json(canvasId)});
if (!(canvas instanceof HTMLCanvasElement)) {
  throw new Error("as3js boot: canvas #${canvasId} is missing");
}
const context = canvas.getContext("2d");
if (!context) throw new Error("as3js boot: a 2D canvas context is required");

const flashVars = globalThis.__as3jsFlashVars;
if (flashVars && typeof flashVars === "object") {
  $setExternalVariables(flashVars, { url: globalThis.location.href, loaderURL: globalThis.location.href });
}
// Flash's SWF embed "base" parameter: the host script sets it before boot runs.
if (typeof globalThis.__as3jsBaseUrl === "string" && globalThis.__as3jsBaseUrl.length > 0) {
  $setBaseUrl(globalThis.__as3jsBaseUrl);
}
$setExternalInterfaceBridge(globalThis.FlashExternalInterface ?? null);

function showError(error) {
  const message = error && error.stack ? error.stack : String(error);
  const panel = document.getElementById("error");
  if (panel) {
    panel.hidden = false;
    panel.textContent = message;
  }
  document.documentElement.dataset.result = "error";
  console.error(error);
}

try {
  const manifest = await fetch("./manifest.json").then((response) => {
    if (!response.ok) throw new Error("manifest.json: HTTP " + response.status);
    return response.json();
  });
  if (typeof manifest.entry !== "string" || manifest.entry.length === 0) {
    throw new Error("as3js boot: manifest.json has no entry class");
  }

  const manager = new AssetManager();
  let archiveBytes = null;
  const archiveResponse = await fetch(${json(`./${assets}`)});
  if (archiveResponse.ok) {
    archiveBytes = new Uint8Array(await archiveResponse.arrayBuffer());
    manager.addBundle("app", PopArchive.fromBytes(archiveBytes));
  } else if (archiveResponse.status !== 404) {
    throw new Error("${assets}: HTTP " + archiveResponse.status);
  }
  $setAssetManager(manager);

  const Stage = $runtimeClass("flash.display.Stage");
  const stage = new Stage();
  // CSS lays the canvas out at the viewport size; its attribute size is only the default
  // 300x150 backing store until the host sets it. Size the stage from the CSS box so the
  // first layout pass (splash centering, preloader) sees the real stage, not 300x150.
  const pixelRatio = Math.max(1, Number(globalThis.devicePixelRatio) || 1);
  const width = Math.max(1, Math.floor(canvas.clientWidth || canvas.width || 1024));
  const height = Math.max(1, Math.floor(canvas.clientHeight || canvas.height || 768));
  // Render at device resolution: a 1x backing store on a 2x display upscales every glyph.
  const sizeBackingStore = (cssWidth, cssHeight) => {
    const backingWidth = Math.max(1, Math.round(cssWidth * pixelRatio));
    const backingHeight = Math.max(1, Math.round(cssHeight * pixelRatio));
    if (canvas.width !== backingWidth) canvas.width = backingWidth;
    if (canvas.height !== backingHeight) canvas.height = backingHeight;
  };
  sizeBackingStore(width, height);
  // Ruffle reads the movie size from the SWF header before the stage is built; a compiled project
  // has no header, so the manifest carries the authored size when the project declares one.
  const authoredStage = Boolean(manifest.stage && manifest.stage.width > 0 && manifest.stage.height > 0);
  if (authoredStage) {
    $setStageMovieSize(stage, manifest.stage.width, manifest.stage.height);
  } else {
    // With no authored size there is nothing to initialize against but the viewport.
    $setStageSize(stage, width, height);
  }

  const entry = $getClass(manifest.entry);
  if (!entry) throw new Error("as3js boot: entry class '" + manifest.entry + "' is not registered by ${bundle}");
  const root = $createRoot(entry, [], stage);
  // The player lays the stage out to its viewport after the SWF's first frame, which is why a Flash
  // client initializes against the authored size and then receives one Stage.RESIZE. Applying the
  // viewport before the root exists would hide that resize, and clients that pin their window
  // layout to stageWidth in the handler would keep the size they were constructed with.
  if (authoredStage) $setStageSize(stage, width, height);
  // getClass lets a host or a debugger reach any compiled type by name, so runtime values can
  // be traced from the page without a source rebuild.
  globalThis.__as3js = { stage, root, manager, manifest, frames: 0, draw: null, getClass: $getClass };
  await $flushEmbeddedAssets();
  if (archiveBytes) {
    // A real loader reports progress before completion; emit both so preloaders that
    // cache byte counts on the first progress event still see the final percentage.
    $setLoaderProgress(stage.loaderInfo, archiveBytes.byteLength, archiveBytes.byteLength);
    $setLoaderProgress(stage.loaderInfo, archiveBytes.byteLength, archiveBytes.byteLength, true);
  }

  // Flash dispatches Stage RESIZE only when the SWF is actually resized (NO_SCALE), never as part
  // of movie startup; the first layout above is that resize.
  const resize = () => {
    const nextWidth = Math.max(1, Math.floor(canvas.clientWidth || width));
    const nextHeight = Math.max(1, Math.floor(canvas.clientHeight || height));
    if (nextWidth !== stage.stageWidth || nextHeight !== stage.stageHeight) {
      sizeBackingStore(nextWidth, nextHeight);
      $setStageSize(stage, nextWidth, nextHeight);
    }
  };
  window.addEventListener("resize", resize);
  // The player tracks its viewport for the whole session: an ancestor reflow can change the
  // canvas box without a window resize event, and the stage has to follow it.
  if (typeof ResizeObserver === "function") new ResizeObserver(resize).observe(canvas);
  resize();

  // Flash clients read pointer input from stage MouseEvents; the window manager hit-tests
  // with stageX/stageY, so the host only has to translate canvas coordinates and dispatch.
  const pointerPoint = (event) => {
    const rect = canvas.getBoundingClientRect();
    return {
      x: rect.width > 0 ? ((event.clientX - rect.left) * stage.stageWidth) / rect.width : event.clientX,
      y: rect.height > 0 ? ((event.clientY - rect.top) * stage.stageHeight) / rect.height : event.clientY,
    };
  };
  const sendMouse = (type, event, extra) => {
    const point = pointerPoint(event);
    $dispatchMouseEvent(stage, type, point.x, point.y, {
      buttonDown: event.buttons > 0,
      ctrlKey: event.ctrlKey,
      altKey: event.altKey,
      shiftKey: event.shiftKey,
      ...(extra || {}),
    });
  };
  canvas.addEventListener("mousemove", (event) => sendMouse("mouseMove", event));
  canvas.addEventListener("mousedown", (event) => {
    event.preventDefault();
    sendMouse("mouseDown", event, { buttonDown: true });
  });
  canvas.addEventListener("mouseup", (event) => sendMouse("mouseUp", event));
  canvas.addEventListener("click", (event) => sendMouse("click", event));
  canvas.addEventListener("dblclick", (event) => sendMouse("doubleClick", event));
  canvas.addEventListener(
    "wheel",
    (event) => sendMouse("mouseWheel", event, { delta: -Math.sign(event.deltaY) * 3 }),
    { passive: true },
  );
  canvas.addEventListener("contextmenu", (event) => event.preventDefault());

  const draw = () => {
    try {
      context.setTransform(pixelRatio, 0, 0, pixelRatio, 0, 0);
      context.clearRect(0, 0, stage.stageWidth, stage.stageHeight);
      $renderDisplay(stage, context);
      globalThis.__as3js.frames += 1;
      requestAnimationFrame(draw);
    } catch (error) {
      showError(error);
    }
  };
  globalThis.__as3js.draw = draw;
  $startFrameLoop(stage, { frameRate: Number(stage.frameRate) || 24 });
  // Render the first frame synchronously. A background tab can throttle rAF indefinitely,
  // but a host that successfully constructed the project should still present its stage.
  draw();
  document.documentElement.dataset.result = "running";
} catch (error) {
  showError(error);
}
`;
}

/** Emits a minimal host page for `browserBoot`. */
export function browserIndex(options: BrowserBootOptions = {}): string {
  const canvasId = options.canvasId ?? "stage";
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>as3js</title>
<style>
html, body { margin: 0; width: 100%; height: 100%; overflow: hidden; background: #101014; }
#${canvasId} { display: block; width: 100vw; height: 100vh; }
#error { position: fixed; inset: 0; overflow: auto; margin: 0; padding: 24px; color: #ffb4b4; background: #1a1010; font: 13px/1.45 ui-monospace, monospace; white-space: pre-wrap; }
</style>
</head>
<body>
<canvas id="${canvasId}"></canvas>
<pre id="error" hidden></pre>
${options.host ? `<script src="./${options.host}"></script>\n` : ""}<script type="module" src="./boot.js"></script>
</body>
</html>
`;
}
