/**
 * Explicit runtime declarations for the Flash Player and Flex symbols used by the
 * measured AS3 corpus. These are declarations, not implementations: the runtime package
 * owns behavior. Keeping them here prevents the resolver from treating an arbitrary
 * unresolved name as a valid external type.
 */
export interface RuntimeParamDeclaration {
  name: string;
  type: string;
  optional?: boolean;
  rest?: boolean;
}

export interface RuntimeMemberDeclaration {
  name: string;
  kind: "field" | "method" | "getter" | "setter";
  type: string;
  params?: RuntimeParamDeclaration[];
  static?: boolean;
  readonly?: boolean;
}

export interface RuntimeTypeDeclaration {
  fqcn: string;
  kind: "class" | "interface";
  base?: string;
  interfaces?: string[];
  members?: RuntimeMemberDeclaration[];
}

export interface RuntimeManifest {
  types: RuntimeTypeDeclaration[];
  packages: string[];
  values: string[];
  namespaces: string[];
}

