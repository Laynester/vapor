function mergeMembers(
  ...groups: Record<string, RuntimeMemberDeclaration[]>[]
): Record<string, RuntimeMemberDeclaration[]> {
  const merged: Record<string, RuntimeMemberDeclaration[]> = {};
  for (const group of groups) {
    for (const [fqcn, members] of Object.entries(group)) {
      merged[fqcn] = [...(merged[fqcn] ?? []), ...members];
    }
  }
  return merged;
}

